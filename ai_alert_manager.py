# SafeDrive AI - AI Alert Manager
# Organises safety warnings by urgency.
# This is a rule-based prototype, not a trained AI model.

SEVERITY_ORDER = {
    "CRITICAL": 1,
    "HIGH": 2,
    "MEDIUM": 3,
    "LOW": 4,
    "UNKNOWN": 5
}


def collect_safety_alerts(
    ai_warnings=None,
    junction_result=None,
    overtaking_result=None,
    pedestrian_result=None
):
    """
    Collect warnings from the SafeDrive AI feature modules
    and sort them from most urgent to least urgent.

    Parameters:
        ai_warnings: List returned by generate_ai_warnings().
        junction_result: Result returned by analyze_junction_risk().
        overtaking_result: Result returned by assess_overtaking_risk().
        pedestrian_result: Result returned by predict_pedestrian_risk().

    Returns:
        A sorted list of alert dictionaries.
    """

    alerts = []

    # 1. Add general driving warnings
    if isinstance(ai_warnings, list):
        for warning in ai_warnings:
            if not isinstance(warning, dict):
                continue

            alerts.append({
                "source": warning.get("type", "General Safety"),
                "level": str(warning.get("level", "UNKNOWN")).upper(),
                "message": warning.get(
                    "message",
                    "Review the current driving conditions."
                )
            })

    # 2. Add junction warning
    if isinstance(junction_result, dict):
        level = str(
            junction_result.get("risk_level", "UNKNOWN")
        ).upper()

        if level in ["HIGH", "CRITICAL", "MEDIUM"]:
            alerts.append({
                "source": "Junction Risk",
                "level": level,
                "message": junction_result.get(
                    "warning",
                    "Approach the junction cautiously."
                )
            })

    # 3. Add overtaking warning
    if isinstance(overtaking_result, dict):
        level = str(
            overtaking_result.get("risk_level", "UNKNOWN")
        ).upper()

        if level in ["HIGH", "CRITICAL", "MEDIUM"]:
            alerts.append({
                "source": "Overtaking Safety",
                "level": level,
                "message": overtaking_result.get(
                    "recommendation",
                    "Verify road conditions before considering overtaking."
                )
            })

    # 4. Add pedestrian warning
    if isinstance(pedestrian_result, dict):
        level = str(
            pedestrian_result.get("risk_level", "UNKNOWN")
        ).upper()

        if level in ["HIGH", "CRITICAL", "MEDIUM"]:
            alerts.append({
                "source": "Pedestrian Safety",
                "level": level,
                "message": pedestrian_result.get(
                    "warning",
                    "Remain alert to pedestrians."
                )
            })

    # 5. Sort alerts by severity
    alerts.sort(
        key=lambda alert: SEVERITY_ORDER.get(
            alert["level"], 5
        )
    )

    return alerts


def get_highest_priority_alert(alerts):
    """
    Return the most urgent alert, or a safe default
    message when no elevated alerts are present.
    """

    if not alerts:
        return {
            "source": "General Safety",
            "level": "LOW",
            "message": (
                "No elevated alerts were generated by the current rules. "
                "Continue following road signs and safe-driving practices."
            )
        }

    return alerts[0]